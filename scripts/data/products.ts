/**
 * The 36-car launch catalogue.
 *
 * Every product is written with every `Product` field. Mechanical fields are derived by
 * `defineProduct` so they cannot drift:
 * - `id` = `slug`; `currency` = 'INR'; `isActive` = true
 * - `seriesName`, `year` and `seriesNumber` come from the series document (`seriesNumber` is the
 *   car's position in the series' `carIds`)
 * - `images` are built from placeholder variants (first = primary, the rest = alternate
 *   colourways) with Cloudinary public ids `hotwheelsarena/cars/<slug>[-n]`;
 *   `primaryImage === images[0].url`
 * - `ratingAvg` / `ratingCount` are NOT set here — they are computed from `reviews.ts`.
 *
 * Catalogue shape (enforced by scripts/lib/validate.ts): 36 cars, every category covered,
 * exactly 8 `isNew` (the 8 newest `createdAt`), exactly 8 `isFeatured`, 6 `isVault` numbered
 * editions with low stock, 2 sold out, prices ₹199–₹2,499.
 * Rarity mix: 18 common · 9 rare · 3 super-rare · 6 limited.
 *
 * Makes and models are real cars reproduced as 1:64 die-cast; the `Garage Originals` cars are
 * original fantasy designs with generic names. `themedStats` are themed, fictional readouts for
 * the "Meet the Machine" panel — not claims about the toy.
 */
import type { ProductImage } from '../../shared/types.ts';
import {
  CAR_VARIANTS,
  CLOUDINARY_CAR_FOLDER,
  placeholderUrl,
  type CarVariantId,
} from './placeholders.ts';
import { SERIES } from './series.ts';
import type { SeedProduct } from './types.ts';

const MATERIAL = {
  mainline: 'Die-cast metal body, plastic base',
  premium: 'Die-cast metal body and base, rubber tyres',
  premium43: 'Die-cast metal body and chassis, rubber tyres, acrylic display base',
  premium18: 'Die-cast metal with opening doors, engine lid and bonnet, rubber tyres',
  truck: 'Die-cast metal cab, plastic body and base',
  fantasy: 'Die-cast metal body, chrome-plated engine, plastic base',
} as const;

/** Maker used for the original (non-licensed) fantasy designs. */
const ORIGINALS = 'Garage Originals';

type DerivedField =
  | 'id'
  | 'seriesName'
  | 'seriesNumber'
  | 'year'
  | 'images'
  | 'primaryImage'
  | 'currency'
  | 'isActive';

interface ProductInput extends Omit<SeedProduct, DerivedField> {
  /** Placeholder variants: the first is the primary image, the rest are alternate colourways. */
  images: readonly [CarVariantId, ...CarVariantId[]];
}

function buildImages(
  slug: string,
  name: string,
  variants: readonly [CarVariantId, ...CarVariantId[]],
): ProductImage[] {
  return variants.map((variant, index) => ({
    publicId: `${CLOUDINARY_CAR_FOLDER}/${slug}${index === 0 ? '' : `-${index + 1}`}`,
    url: placeholderUrl(variant),
    alt:
      index === 0
        ? `${name} in ${CAR_VARIANTS[variant].label} — side view`
        : `${name} — alternate ${CAR_VARIANTS[variant].label} colourway`,
  }));
}

/**
 * Completes a product from its editorial fields. Unknown series / unlisted cars produce
 * `seriesNumber: 0` / `year: 0`, which the validator reports instead of crashing here.
 */
export function defineProduct(input: ProductInput): SeedProduct {
  const series = SERIES.find((entry) => entry.id === input.series);
  const position = series ? series.carIds.indexOf(input.slug) + 1 : 0;
  return {
    ...input,
    id: input.slug,
    seriesName: series?.name ?? '',
    seriesNumber: position,
    year: series?.year ?? 0,
    currency: 'INR',
    images: buildImages(input.slug, input.name, input.images),
    primaryImage: placeholderUrl(input.images[0]),
    isActive: true,
  };
}

